def day_list():
    out = []
    for i, d in enumerate(DAYS):
        date = START + dt.timedelta(days=i)
        hol = HOLIDAYS.get(date)
        is_h = date.weekday() >= 5 or hol is not None
        out.append({'day': i + 1, 'date': date, 'wd': WD[date.weekday()], 'holiday': hol, 'is_h': is_h, 'tasks': d})
    return out


def unit_title(subj, code):
    if subj == 'J' and code.startswith('K') and code[1:].isdigit():
        return '漢字セット%s' % code[1:]
    return UNITS[subj][code][0]


def unit_min(subj, code):
    if subj == 'J' and code.startswith('K') and code[1:].isdigit():
        return 10
    return UNITS[subj][code][1]


